use crate::expose::api_scan::FfiType;
use crate::expose::path_native::PathNativeBuild;
use crate::manifest::Dependency;
use anyhow::{Context, Result};
use std::path::Path;

pub fn write_rust_reexport(out: &Path, name: &str, dep: &Dependency) -> Result<()> {
    let crate_ident = name.replace('-', "_");
    let ver = dep.version.as_deref().unwrap_or("*");
    let body = format!(
        r#"//! Auto-exposed by rig — Rust host re-export of `{name}` ({ver}).
//! Native in-process path: link as a normal Cargo dependency, then `use` this module.
//! For cross-lang hosts, equilibrium-ffi generates consumer imports from a C ABI surface.
#![allow(unused_imports)]

pub use {crate_ident}::*;

/// Marker that rig wired `{name}` into this project.
pub fn rig_native_{crate_ident}() -> &'static str {{
    "{name}"
}}

/// Documents the equilibrium-ffi load path when a foreign/cdylib surface is available.
pub fn rig_equilibrium_hint_{crate_ident}() -> &'static str {{
    "equilibrium_ffi::load / generate_imports — see https://github.com/tschk/equilibrium"
}}
"#
    );
    std::fs::write(out, body).with_context(|| format!("write {}", out.display()))?;
    Ok(())
}

/// Rust binder for a path/git native library rig built into `built.native_dir`:
/// `#[link]` + `extern "C"` declarations for the discovered C prototypes.
/// The link search path and rpath come from rig's block in `build.rs`.
pub fn write_rust_path_native(
    out: &Path,
    name: &str,
    dep: &Dependency,
    built: &PathNativeBuild,
) -> Result<()> {
    let mut exports = crate::expose::c_header_scan::scan_headers(&built.headers);
    if dep.ecosystem == "zig" || built.source_root.join("root.zig").is_file() {
        for e in crate::expose::zig_export_scan::scan_zig_sources(&built.source_root) {
            if !exports.iter().any(|x| x.export_name == e.export_name) {
                exports.push(e);
            }
        }
    }
    let mut decls = String::new();
    for e in &exports {
        let params = e
            .params
            .iter()
            .map(|p| format!("{}: {}", p.name, p.ty.rust_ty()))
            .collect::<Vec<_>>()
            .join(", ");
        let ret = if e.ret == FfiType::Void {
            String::new()
        } else {
            format!(" -> {}", e.ret.rust_ty())
        };
        decls.push_str(&format!("    pub fn {}({params}){ret};\n", e.export_name));
    }
    if decls.is_empty() {
        decls.push_str(
            "    // No C prototypes discovered in the package headers; declare the\n    // symbols you need in your own `extern \"C\"` block linking the same library.\n",
        );
    }
    let body = format!(
        r#"//! Auto-generated by rig — Rust host ← {eco} package `{name}` (path/git).
//! Native library `{lib}` built into `{dir}`; `build.rs` (rig-link block) adds
//! the link search path and, on Unix, an rpath. On Windows the DLL must be on
//! `PATH` or beside the executable at run time. Do not edit — regenerate with `rig sync`.
#![allow(dead_code, unused_imports, non_snake_case, clippy::all)]

use core::ffi::{{c_char, c_void}};

// Windows: raw-dylib needs no import library (`{lib}.lib`) for the DLL.
#[cfg_attr(windows, link(name = "{lib}", kind = "raw-dylib"))]
#[cfg_attr(not(windows), link(name = "{lib}", kind = "dylib"))]
unsafe extern "C" {{
{decls}}}
"#,
        eco = dep.ecosystem,
        lib = built.lib_name,
        dir = built.native_rel,
    );
    std::fs::write(out, body).with_context(|| format!("write {}", out.display()))?;
    Ok(())
}
