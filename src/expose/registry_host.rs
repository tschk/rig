//! Registry dependencies consumed by the host's own package manager:
//! NuGet packages → `<PackageReference>` in the `.csproj`, dub packages →
//! `dependencies` in `dub.json` / `dub.sdl`. Path pins become a
//! `<ProjectReference>` / dub `path` dependency.

use crate::manifest::Dependency;
use crate::util::AppCtx;
use anyhow::{Context, Result, bail};
use std::path::{Path, PathBuf};

const CSPROJ_BEGIN: &str = "  <!-- rig:begin — generated by rig from rig.toml; do not edit -->\n";
const CSPROJ_END: &str = "  <!-- rig:end -->\n";

/// The host project file: `[host].manifest` if set, else the single `*.csproj`.
fn host_csproj(ctx: &AppCtx) -> Result<PathBuf> {
    if let Some(m) = &ctx.manifest.host.manifest {
        return Ok(ctx.root.join(m));
    }
    let mut found: Vec<PathBuf> = std::fs::read_dir(&ctx.root)?
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|e| e == "csproj"))
        .collect();
    found.sort();
    match found.len() {
        1 => Ok(found.remove(0)),
        0 => bail!(
            "no .csproj in {}; set [host].manifest in rig.toml",
            ctx.root.display()
        ),
        _ => bail!(
            "several .csproj files in {}; set [host].manifest in rig.toml",
            ctx.root.display()
        ),
    }
}

fn xml_attr(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('"', "&quot;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

fn csharp_reference(ctx: &AppCtx, name: &str, dep: &Dependency) -> Result<String> {
    if let Some(path) = &dep.path {
        let dir = ctx.root.join(path);
        let proj = if dir.extension().is_some_and(|e| e == "csproj") {
            dir
        } else {
            std::fs::read_dir(&dir)
                .with_context(|| format!("read {}", dir.display()))?
                .flatten()
                .map(|e| e.path())
                .find(|p| p.extension().is_some_and(|e| e == "csproj"))
                .with_context(|| format!("no .csproj under {} for `{name}`", dir.display()))?
        };
        return Ok(format!(
            "    <ProjectReference Include=\"{}\" />\n",
            xml_attr(&proj.display().to_string())
        ));
    }
    if dep.git.is_some() || dep.url.is_some() {
        bail!(
            "C# dependency `{name}`: NuGet has no git/url sources; clone it and use path:<dir with .csproj>"
        );
    }
    let ver = dep
        .version
        .as_deref()
        .filter(|v| !matches!(*v, "*" | "path" | "git"))
        .with_context(|| format!("C# dependency `{name}` has no pinned version"))?;
    Ok(format!(
        "    <PackageReference Include=\"{}\" Version=\"{}\" />\n",
        xml_attr(name),
        xml_attr(ver)
    ))
}

/// Regenerate rig's `<ItemGroup>` in the host `.csproj` from every `csharp`
/// dependency in rig.toml (removing it when there are none).
pub fn sync_csproj(ctx: &AppCtx) -> Result<PathBuf> {
    let csproj = host_csproj(ctx)?;
    let text =
        std::fs::read_to_string(&csproj).with_context(|| format!("read {}", csproj.display()))?;
    let mut items = String::new();
    for (name, dep) in &ctx.manifest.dependencies {
        if dep.ecosystem == "csharp" {
            items.push_str(&csharp_reference(ctx, name, dep)?);
        }
    }
    let mut body = match (text.find(CSPROJ_BEGIN), text.find(CSPROJ_END)) {
        (Some(b), Some(e)) if e > b => format!("{}{}", &text[..b], &text[e + CSPROJ_END.len()..]),
        _ => text.clone(),
    };
    if !items.is_empty() {
        let at = body
            .rfind("</Project>")
            .with_context(|| format!("{} has no </Project>", csproj.display()))?;
        body.insert_str(
            at,
            &format!(
                "{CSPROJ_BEGIN}  <ItemGroup Label=\"rig\">\n{items}  </ItemGroup>\n{CSPROJ_END}"
            ),
        );
    }
    if body != text {
        std::fs::write(&csproj, body)?;
    }
    Ok(csproj)
}

fn dub_value(ctx: &AppCtx, name: &str, dep: &Dependency) -> Result<DubDep> {
    if let Some(path) = &dep.path {
        return Ok(DubDep::Path(ctx.root.join(path).display().to_string()));
    }
    if dep.git.is_some() || dep.url.is_some() {
        bail!(
            "D dependency `{name}`: dub needs a registry version or path:; clone the git repo and use path:"
        );
    }
    let ver = dep
        .version
        .as_deref()
        .filter(|v| !matches!(*v, "*" | "path" | "git"))
        .with_context(|| format!("D dependency `{name}` has no pinned version"))?;
    Ok(DubDep::Version(ver.to_string()))
}

enum DubDep {
    Version(String),
    Path(String),
}

/// Add (`Some`) or remove (`None`) one dependency in the host `dub.json` / `dub.sdl`.
fn set_dub_dep(root: &Path, name: &str, value: Option<DubDep>) -> Result<PathBuf> {
    let json = root.join("dub.json");
    if json.is_file() {
        let text = std::fs::read_to_string(&json)?;
        let mut doc: serde_json::Value =
            serde_json::from_str(&text).with_context(|| format!("parse {}", json.display()))?;
        let obj = doc.as_object_mut().context("dub.json is not an object")?;
        match value {
            Some(v) => {
                let deps = obj
                    .entry("dependencies")
                    .or_insert_with(|| serde_json::json!({}))
                    .as_object_mut()
                    .context("dub.json dependencies is not an object")?;
                deps.insert(
                    name.to_string(),
                    match v {
                        DubDep::Version(v) => serde_json::Value::String(v),
                        DubDep::Path(p) => serde_json::json!({ "path": p }),
                    },
                );
            }
            None => {
                if let Some(deps) = obj.get_mut("dependencies").and_then(|d| d.as_object_mut()) {
                    deps.remove(name);
                }
            }
        }
        let out = serde_json::to_string_pretty(&doc)? + "\n";
        if out != text {
            std::fs::write(&json, out)?;
        }
        return Ok(json);
    }
    let sdl = root.join("dub.sdl");
    if sdl.is_file() {
        let text = std::fs::read_to_string(&sdl)?;
        let prefix = format!("dependency \"{name}\"");
        let mut lines: Vec<String> = text
            .lines()
            .filter(|l| !l.trim_start().starts_with(&prefix))
            .map(str::to_string)
            .collect();
        if let Some(v) = value {
            lines.push(match v {
                DubDep::Version(v) => format!("{prefix} version=\"{v}\""),
                DubDep::Path(p) => format!("{prefix} path=\"{p}\""),
            });
        }
        let out = lines.join("\n") + "\n";
        if out != text {
            std::fs::write(&sdl, out)?;
        }
        return Ok(sdl);
    }
    bail!("no dub.json or dub.sdl in {}", root.display())
}

pub fn add_dub_dep(ctx: &AppCtx, name: &str, dep: &Dependency) -> Result<PathBuf> {
    let value = dub_value(ctx, name, dep)?;
    set_dub_dep(&ctx.root, name, Some(value))
}

pub fn remove_dub_dep(root: &Path, name: &str) -> Result<()> {
    set_dub_dep(root, name, None).map(|_| ())
}
